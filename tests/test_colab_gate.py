def _failing_fetch():
    raise OSError("no network in the unit suite")


def test_manifest_prefers_the_live_fetch_and_refreshes_the_cache(tmp_path):
    cache = tmp_path / "colab_pip_freeze.txt"

    packages, source, date, notes = cg.load_manifest(
        cache, fetcher=lambda: MANIFEST_SAMPLE
    )

    assert source == "live"
    assert date is not None
    assert notes == []
    assert packages["optax"] == "0.2.8"
    # The live copy is cached so the next offline run reads today's manifest
    # rather than falling all the way back to the vendored snapshot.
    assert cg.parse_manifest(cache.read_text())["optax"] == "0.2.8"


def test_manifest_falls_back_to_the_cache_when_the_fetch_fails(tmp_path):
    cache = tmp_path / "colab_pip_freeze.txt"
    cache.write_text("cached-only==9.9.9\n")

    packages, source, date, notes = cg.load_manifest(cache, fetcher=_failing_fetch)

    assert source == "cache"
    assert packages == {"cached-only": "9.9.9"}
    assert date is not None
    assert any("live fetch failed" in note for note in notes)


def test_manifest_falls_back_to_the_snapshot_when_there_is_no_cache(tmp_path):
    snapshot = tmp_path / "snapshot.txt"
    snapshot.write_text(
        "# source: googlecolab/backend-info pip-freeze.txt fetched 2026-09-15\n"
        "snapshot-only==1.2.3\n"
    )

    packages, source, date, notes = cg.load_manifest(
        tmp_path / "missing-cache.txt", snapshot_path=snapshot, fetcher=_failing_fetch
    )

    assert source == "snapshot"
    assert date == "2026-09-15"
    assert packages == {"snapshot-only": "1.2.3"}


def test_an_empty_live_manifest_is_not_trusted(tmp_path):
    """A 200 with an empty body must not seed an empty Colab."""
    packages, source, _, notes = cg.load_manifest(
        tmp_path / "missing-cache.txt", fetcher=lambda: ""
    )

    assert source == "snapshot"
    assert len(packages) > 500
    assert any("zero pins" in note for note in notes)


