def test_walk_completes_a_no_deps_install_from_colabs_own_package_set():
    """The IPython/pickleshare regression.

    The seed installs the closure ∩ manifest `--no-deps`, so a seeded package's
    own runtime dependencies only land if the PyAuto closure happened to need
    them too. Colab ships IPython 7.34.0, which needs pickleshare, and nothing
    in the autolens closure does — so `import jax` (which reaches IPython via
    its Colab debugger) died on a package Colab has always had. Colab is
    internally consistent; the simulation has to be too.
    """
    requires = {"ipython": ["pickleshare", "jedi>=0.16"], "pickleshare": [], "jedi": []}
    installed = {"ipython": "7.34.0"}
    manifest = {"pickleshare": "0.7.5", "jedi": "0.19.2"}

    def install(pins):
        for pin in pins:
            name, _, version = pin.partition("==")
            installed[cg.normalise(name)] = version
        return True, ""

    result = cg.walk_requirements(
        ["ipython"],
        manifest,
        installed_version=lambda name: installed.get(cg.normalise(name)),
        requirements=lambda name: requires.get(cg.normalise(name), []),
        install=install,
    )

    assert sorted(e["name"] for e in result["colab_installed"]) == ["jedi", "pickleshare"]
    assert installed["pickleshare"] == "0.7.5"
    # Nothing absent from the manifest is ever installed by the completion pass.
    assert result["missing_declared"] == []


def test_module_dist_candidates_inverts_the_alias_table():
    # A module whose distribution is named differently still has to be
    # recognisable in the Colab manifest.
    assert "scikit-learn" in cg.module_dist_candidates("sklearn")
    assert "pyyaml" in cg.module_dist_candidates("yaml")
    assert "nautilus-sampler" in cg.module_dist_candidates("nautilus")
    # The ordinary case: the module name is the distribution name.
    assert cg.module_dist_candidates("numba") == {"numba"}
