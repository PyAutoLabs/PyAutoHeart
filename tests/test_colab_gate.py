@pytest.fixture
def fake_dists():
    """A fabricated distribution graph: requires + installed versions."""
    requires = {
        "autofit": [
            "numpy>=2.0",
            "corner",
            "xxhash<=3.4.1",
            "dynesty==2.1.5",
            'optax>=0.2.5; sys_platform != "darwin"',
            'anesthetic>=2.9.0; extra == "optional"',
            'windows-only-thing; sys_platform == "win32"',
        ],
        "numpy": [],
        "xxhash": [],
    }
    installed = {"autofit": "2026.9.1.1", "numpy": "2.1.3", "xxhash": "4.0.1"}
    return requires, installed


def walk(fake_dists, manifest, install=None):
    requires, installed = fake_dists
    return cg.walk_requirements(
        ["autofit"],
        manifest,
        installed_version=lambda name: installed.get(cg.normalise(name)),
        requirements=lambda name: requires.get(cg.normalise(name), []),
        install=install,
    )


def test_walk_separates_colab_provided_missing_and_conflicting(fake_dists):
    manifest = {"numpy": "2.1.3", "xxhash": "4.0.1", "optax": "0.2.8"}

    result = walk(fake_dists, manifest)

    missing = {entry["name"] for entry in result["missing_declared"]}
    requested = {entry["name"] for entry in result["colab_installed"]}
    conflicts = {entry["name"]: entry for entry in result["version_conflict"]}

    # Absent AND not shipped by Colab: the hole the --no-deps bootstrap leaves.
    assert missing == {"corner", "dynesty"}
    # Absent but Colab ships it: install Colab's pin, not the declared floor.
    assert requested == {"optax"}
    assert result["colab_installed"][0]["version"] == "0.2.8"
    # Installed, but outside what autofit declares.
    assert set(conflicts) == {"xxhash"}
    assert conflicts["xxhash"]["installed"] == "4.0.1"
    assert conflicts["xxhash"]["specifier"] == "<=3.4.1"
    assert conflicts["xxhash"]["required_by"] == ["autofit"]


def test_walk_skips_extra_markers_and_false_environment_markers(fake_dists):
    result = walk(fake_dists, {"numpy": "2.1.3", "xxhash": "4.0.1", "optax": "0.2.8"})

    names = {entry["name"] for entry in result["missing_declared"]}
    # Behind `extra == "optional"`: not part of a plain `pip install autofit`.
    assert "anesthetic" not in names
    # Behind a marker that is false on Colab (always linux).
    assert "windows-only-thing" not in names


def test_walk_records_who_declared_a_missing_requirement(fake_dists):
    result = walk(fake_dists, {})

    corner = next(e for e in result["missing_declared"] if e["name"] == "corner")
    assert corner["required_by"] == ["autofit"]


def test_walk_continues_through_packages_it_installs_from_colab():
    requires = {
        "autofit": ["mid-package"],
        "mid-package": ["leaf-package"],
        "leaf-package": [],
    }
    installed = {"autofit": "1.0"}
    installs: list[list[str]] = []

    def install(pins):
        installs.append(list(pins))
        for pin in pins:
            name, _, version = pin.partition("==")
            installed[cg.normalise(name)] = version
        return True, ""

    result = cg.walk_requirements(
        ["autofit"],
        {"mid-package": "3.0"},
        installed_version=lambda name: installed.get(cg.normalise(name)),
        requirements=lambda name: requires.get(cg.normalise(name), []),
        install=install,
    )

    # mid-package installed from Colab's pin, then walked, exposing leaf-package
    # — which Colab does NOT ship, so it surfaces as a real hole.
    assert installs == [["mid-package==3.0"]]
    assert [e["name"] for e in result["colab_installed"]] == ["mid-package"]
    assert [e["name"] for e in result["missing_declared"]] == ["leaf-package"]
    assert result["rounds"] >= 2


def test_walk_reports_a_colab_pin_that_will_not_install():
    def install(pins):
        return False, "ERROR: no matching distribution"

    result = cg.walk_requirements(
        ["autofit"],
        {"broken-package": "1.0"},
        installed_version=lambda name: {"autofit": "1.0"}.get(cg.normalise(name)),
        requirements=lambda name: ["broken-package"] if name == "autofit" else [],
        install=install,
    )

    assert [e["name"] for e in result["missing_declared"]] == ["broken-package"]
    assert "no matching distribution" in result["missing_declared"][0]["note"]


