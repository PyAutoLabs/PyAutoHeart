def test_accepted_missing_downgrades_a_fail_to_a_warning():
    unguarded = [
        {
            "module": "corner",
            "error": "ModuleNotFoundError",
            "sites": [{"file": "autofit/plot.py", "line": 95, "guarded": False}],
        }
    ]

    blocking = _verdict(import_failures_unguarded=unguarded, imported_modules=["corner"])
