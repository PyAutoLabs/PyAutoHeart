MANIFEST_SAMPLE = textwrap.dedent(
    """\
    # Do not modify this file directly; it is generated by a script.
    #  $ python3 -m pip freeze

    absl-py==1.4.0
    SQLAlchemy==2.0.52
    typing_extensions==4.16.0
    requests[socks]==2.32.3
    torch @ https://download.pytorch.org/whl/cu124/torch-2.8.0.whl
    some-vcs-package @ git+https://github.com/x/y@main
    -e /content/editable
    unpinned-package
    optax==0.2.8
    """
)


def test_manifest_parsing_keeps_pins_and_normalises_names():
    packages = cg.parse_manifest(MANIFEST_SAMPLE)

    assert packages["absl-py"] == "1.4.0"
    assert packages["optax"] == "0.2.8"
    # PEP 503: case folded, separators unified.
    assert packages["sqlalchemy"] == "2.0.52"
    assert packages["typing-extensions"] == "4.16.0"
    # Extras are not part of the name.
    assert packages["requests"] == "2.32.3"


def test_manifest_parsing_skips_everything_that_is_not_a_pin():
    packages = cg.parse_manifest(MANIFEST_SAMPLE)

    # Direct references and VCS installs name no installable version.
    assert "torch" not in packages
    assert "some-vcs-package" not in packages
    # Editables, comments, blanks and bare names are not pins either.
    assert "editable" not in packages
    assert "unpinned-package" not in packages
    assert not any(name.startswith("#") for name in packages)


def test_vendored_snapshot_parses_and_carries_its_fetch_date():
    text = cg.SNAPSHOT_PATH.read_text()
    packages = cg.parse_manifest(text)

    assert len(packages) > 500
    assert cg._snapshot_date(text) is not None
    # The package set the gate exists to reason about.
    assert "optax" in packages and "xxhash" in packages and "jax" in packages
    for absent in ("corner", "emcee", "dynesty", "blackjax", "nautilus-sampler"):
        assert absent not in packages, f"{absent} is not shipped by Colab"


