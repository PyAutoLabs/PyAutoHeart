def test_scanner_finds_imports_at_any_depth_and_marks_guarding():
    source = textwrap.dedent(
        """\
        import numpy as np
        from astropy.io import fits


        def plot(samples):
            import corner            # the lazy import that detonates on Colab

            return corner.corner(samples)


        def optional():
            try:
                import zeus
            except ImportError:
                zeus = None
            return zeus


        def broadly_guarded():
            try:
                import hmf
            except Exception:
                return None


        def bare_guard():
            try:
                import colossus
            except:  # noqa: E722
                return None
        """
    )

    found = cg.scan_imports_source(source, "autofit/plot.py")
    by_name = {name: (line, guarded) for name, line, guarded in found}

    assert by_name["numpy"] == (1, False)
    # `from a.b import c` is attributed to the top-level distribution module.
    assert by_name["astropy"] == (2, False)
    # Function-level and unguarded: exactly the corner case.
    assert by_name["corner"] == (6, False)
    # try/except ImportError, try/except Exception and a bare except all guard.
    assert by_name["zeus"][1] is True
    assert by_name["hmf"][1] is True
    assert by_name["colossus"][1] is True


def test_scanner_excludes_relative_imports():
    found = cg.scan_imports_source(
        "from . import mask\nfrom ..operators import transformer\n", "autoarray/x.py"
    )

    assert found == []


def test_scanner_does_not_treat_except_or_finally_bodies_as_guarded():
    source = textwrap.dedent(
        """\
        try:
            import fast_thing
        except ImportError:
            import slow_thing
        else:
            import else_thing
        finally:
            import finally_thing
        """
    )

    guarded = {name: g for name, _, g in cg.scan_imports_source(source, "x.py")}

    assert guarded["fast_thing"] is True
    # A fallback import is the thing that must work, so it is not guarded.
    assert guarded["slow_thing"] is False
    assert guarded["else_thing"] is False
    assert guarded["finally_thing"] is False


def test_scanner_survives_a_file_it_cannot_parse():
    assert cg.scan_imports_source("def broken(:\n", "x.py") == []


def test_package_scan_drops_stdlib_pyauto_and_dunder_future(tmp_path):
    package = tmp_path / "autofit"
    (package / "sub").mkdir(parents=True)
    (package / "__init__.py").write_text(
        "from __future__ import annotations\n"
        "import os\nimport json\nimport pathlib\n"
        "import autoarray\nimport autolens\n"
        "import numpy\n"
    )
    (package / "sub" / "deep.py").write_text("def f():\n    import corner\n")

    sites = cg.scan_package_imports({"autofit": package})

    assert set(sites) == {"numpy", "corner"}
    # The site is reported repo-relative so a FAIL line points at a real file.
    assert sites["corner"][0]["file"] == "autofit/sub/deep.py"
    assert sites["corner"][0]["line"] == 2
    assert sites["corner"][0]["guarded"] is False


