"""tests/test_colab_gate.py — the Colab package-set gate's pure rules.

Every test here is offline and venv-free: the gate is deliberately split so
manifest parsing, the closure intersection, the requirement walk, the AST
import scan and the verdict are pure functions the suite can pin. The parts
that need a network or a throwaway venv (the live fetch, `pip --dry-run`, the
import probe) are exercised by running `verify_install F` for real.
"""

